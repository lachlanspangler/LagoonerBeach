/** How often each species' condition is met per simulated day (same day model as catch-sim). */
import { applyMove, newGame } from '../src/core/game.ts';
import { newPuzzleGame, puzzleStatus } from '../src/core/puzzle.ts';
import { Rng } from '../src/core/rng.ts';
import { humanBot } from '../src/sim/bots.ts';
import { SPECIES } from '../src/meta/creatures.ts';
import { contextsFor } from '../src/meta/catch.ts';
import pack from '../src/content/puzzles.json';
const DAYS = 8;
const hits: Record<string, number> = {};
const count = (ctxs: ReturnType<typeof contextsFor>) => {
  for (const c of ctxs) for (const s of SPECIES) if (s.when(c)) hits[s.id] = (hits[s.id] ?? 0) + 1;
};
let reef = 0;
for (let d = 1; d <= DAYS; d++) {
  for (let g = 0; g < 6; g++) {
    const mode = g === 5 ? 'daily' : 'classic';
    const seed = d * 100 + g;
    const night = g < 2;
    let s = newGame(seed, { mode });
    const r = new Rng(seed);
    while (!s.over && s.moves < 400) {
      const res = applyMove(s, humanBot(s, r)!)!;
      for (const e of res.events)
        if (e.type === 'captured')
          count(
            contextsFor(
              { waves: e.waves, streak: e.streak, clean: e.score.cleanBonus > 0 },
              { gameSeed: seed, move: res.state.moves, night, mode },
            ),
          );
      s = res.state;
    }
  }
  // reefs: sample across the whole pack (players pick reefs freely)
  for (let k = 0; k < 3; k++, reef = (reef + 37) % pack.length) {
    const p = pack[reef] as any;
    let s = newPuzzleGame(p, reef);
    for (const m of p.solution) {
      const res = applyMove(s, { slot: m.piece, x: m.x, y: m.y })!;
      const win = puzzleStatus(res.state) === 'solved';
      for (const e of res.events)
        if (e.type === 'captured')
          count(
            contextsFor(
              { waves: e.waves, streak: e.streak, clean: false },
              { gameSeed: reef, move: res.state.moves, night: false, mode: 'puzzle', tier: p.tier, reefWin: win },
            ),
          );
      s = res.state;
    }
  }
}
const rows = SPECIES.map((s) => [s.id, s.rarity, (hits[s.id] ?? 0) / DAYS] as const);
console.log(JSON.stringify(Object.fromEntries(rows.map(([id, , r]) => [id, +r.toFixed(2)]))));
for (const [id, rar, r] of rows) console.log(id.padEnd(12), rar.padEnd(10), r.toFixed(2));

// --write: derive per-species chances so the expected first catch lands near a target day
if (process.argv.includes('--write')) {
  const { writeFileSync } = await import('node:fs');
  const TARGET: Record<string, number> = { uncommon: 3.5, rare: 12, epic: 22, legendary: 30 };
  const FLOOR = 0.5; // a player chasing a hint makes even rare shapes ~every other day
  const out: Record<string, number> = {};
  for (const [id, rar, r] of rows) {
    if (rar === 'common') continue;
    out[id] = +Math.min(1, 1 / (TARGET[rar]! * Math.max(r, FLOOR))).toFixed(4);
  }
  writeFileSync(
    'src/meta/catchTuning.ts',
    `/** Generated by \`npx tsx scripts/catch-rates.ts --write\` from simulated play (see ADR 0007). */\nexport const CHANCE_BY_ID: Readonly<Record<string, number>> = ${JSON.stringify(out, null, 2)};\n`,
  );
  console.log('wrote src/meta/catchTuning.ts');
}
