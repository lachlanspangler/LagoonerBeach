/**
 * The creature lint report: every registered species against the validator, grouped by rule.
 *   npm run art:lint        → writes docs/art/LINT.md (ART_LINT_WRITE=1)
 *   ART_LINT_STRICT=1 …     → warnings fail too (the lead flips this after the fleet redo)
 * In a plain `make check` it only asserts there are no errors (art.test.ts does the same per species);
 * it never rewrites the file, so parallel fleet branches don't conflict on a generated doc.
 */
import { describe, expect, it } from 'vitest';
import { writeFileSync } from 'node:fs';
import { SPECIES, SPECIES_BY_ID } from '../../src/meta/creatures.ts';
import { ART } from '../../src/render/art/species/index.ts';
import { failing, LINT, LINT_AS_ERRORS, metrics, validateArt, type Issue } from '../../src/render/art/validate.ts';

const RULES: Record<string, string> = {
  R7F: `eye below the absolute floor (≥ 4 CSS px in the 54 px tile, ≥ 9 % of box height) — CRITIQUE-1 #2`,
  R5T: `body tilted more than ${LINT.tiltMax}° at rest (fish / shark / horse / long) — #3`,
  R28: 'XL frame-break not 2–4 px past the art box, or clipped by the 8 px bleed — #4',
  R18E: `eye-coloured pattern within ${LINT.eyeNear} eye-widths of the eye — #5`,
  R18W: `pattern strokes < ${LINT.patternStripMin} u or dots < ${LINT.patternDotMin} u — #5 / R18`,
  R2L: `interior detail line < ${LINT.lineMin} u — R2`,
  R16S: `body chroma < ${LINT.chromaMin} (browns sink on Day) — #5`,
  R16M: `body too close to the real journal tile (mint) — CRITIQUE-1 "review on mint"`,
};

describe('creature lint report', () => {
  const strict = LINT_AS_ERRORS || process.env.ART_LINT_STRICT === '1';
  const rows = [...ART.values()].map((a) => ({ a, issues: validateArt(a, SPECIES_BY_ID.get(a.id)) }));

  it('no species has validator errors (warnings are listed in docs/art/LINT.md)', () => {
    for (const { a, issues } of rows) expect(failing(issues, strict), a.id).toEqual([]);
  });

  it.runIf(process.env.ART_LINT_WRITE === '1')('writes docs/art/LINT.md', () => {
    const order = SPECIES.map((s) => s.id).filter((id) => ART.has(id));
    const byRule = new Map<string, string[]>();
    for (const { a, issues } of rows)
      for (const i of issues.filter((x) => x.level === 'warn'))
        if (!byRule.get(i.rule)?.includes(a.id)) byRule.set(i.rule, [...(byRule.get(i.rule) ?? []), a.id]);
    const clean = rows.filter((r) => !r.issues.length).map((r) => r.a.id);
    const lines = [
      '# Creature lint report',
      '',
      'Generated by `npm run art:lint` (tests/unit/art-lint.test.ts) from `src/render/art/validate.ts`.',
      'CRITIQUE-1 rules are **warnings** for now: `make check` passes, and they become errors when',
      '`LINT_AS_ERRORS` is flipped (or with `ART_LINT_STRICT=1`) after the fleet redo. See',
      '`docs/art/CRITIQUE-1.md` and `docs/art/FLEET_BRIEF.md` §4.',
      '',
      `${rows.length} species · ${rows.length - clean.length} with warnings · clean: ${clean.join(', ') || '—'}`,
      '',
      '## By rule',
      '',
      '| rule | what | species |',
      '|---|---|---|',
      ...Object.keys(RULES).map(
        (r) =>
          `| ${r} | ${RULES[r]} | ${(byRule.get(r) ?? []).sort((x, y) => order.indexOf(x) - order.indexOf(y)).join(', ') || '—'} |`,
      ),
      '',
      '## By species',
      '',
      '| species | size | eye u (floor) | tilt | XL break px | warnings |',
      '|---|---|---|---|---|---|',
      ...order.map((id) => {
        const r = rows.find((x) => x.a.id === id)!;
        const m = metrics(r.a);
        const w = r.issues.filter((i: Issue) => i.level === 'warn');
        return `| ${id} | ${r.a.size} | ${m.eye.toFixed(1)} (${m.eyeFloor.toFixed(1)}) | ${Math.round(m.tilt)}° | ${r.a.size === 'XL' ? m.overhang.toFixed(1) : ''} | ${w.map((i) => `**${i.rule}** ${i.msg}`).join('<br>') || '✓'} |`;
      }),
      '',
    ];
    writeFileSync('docs/art/LINT.md', lines.join('\n'));
  });
});
